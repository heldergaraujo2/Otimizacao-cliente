#!/usr/bin/env node
/**
 * Writes a **synthetic** MU data directory in the classic server-side layout, so the browser client
 * can be tried end to end (gateway `--data-dir`) without any proprietary files:
 *
 *   assets-local/demo-data/World1/EncTerrain1.att
 *   assets-local/demo-data/World1/EncTerrain1.map
 *   assets-local/demo-data/World1/EncTerrain1.obj
 *   assets-local/demo-data/World1/TileGrass.OZT      (terrain texture, 64x64)
 *   assets-local/demo-data/World1/TileWater.OZT
 *   assets-local/demo-data/Player/Player.bmd         (synthetic character model)
 *
 * Nothing here comes from the game — every byte is generated by `@mu-reengineer/formats` fixtures.
 * Real data is used the same way: point `--data-dir` (or `MU_REENGINEER_DATA`) at a real tree.
 *
 * Usage: node scripts/make-demo-data.mjs [--out assets-local/demo-data]
 */

import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import {
  buildAttFixture,
  buildBmdFixture,
  buildMapFixture,
  buildObjFixture,
  buildOztFixture,
} from '@mu-reengineer/formats';

const argv = process.argv.slice(2);
const outIndex = argv.indexOf('--out');
const out = outIndex >= 0 ? argv[outIndex + 1] : 'assets-local/demo-data';
if (!out) {
  process.stderr.write('error: --out needs a path\n');
  process.exit(2);
}

const world = join(out, 'World1');
const player = join(out, 'Player');
await mkdir(world, { recursive: true });
await mkdir(player, { recursive: true });

const files = {
  [join(world, 'EncTerrain1.att')]: buildAttFixture({ extended: true }).bytes,
  [join(world, 'EncTerrain1.map')]: buildMapFixture().bytes,
  [join(world, 'EncTerrain1.obj')]: buildObjFixture().bytes,
  [join(world, 'TileGrass.OZT')]: buildOztFixture(64, 64).bytes,
  [join(world, 'TileWater.OZT')]: buildOztFixture(64, 64).bytes,
  [join(player, 'Player.bmd')]: buildBmdFixture({ version: 15, name: 'synthetic-hero' }).bytes,
};

for (const [path, bytes] of Object.entries(files)) {
  await writeFile(path, bytes);
  process.stdout.write(`${path}  ${bytes.length} B\n`);
}
process.stdout.write(`\ndemo data written to ${out} — start the gateway with:\n  node tools/mu-gateway/dist/index.js --ws-port 7788 --server --data-dir ${out}\n`);
